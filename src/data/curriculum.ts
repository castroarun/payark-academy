// ─────────────────────────────────────────────────────────────
// Lookup Helpers
// ─────────────────────────────────────────────────────────────

export function getModule(id: string): Module | undefined {
  return modules.find((m) => m.id === id);
}

export function getModulesByLevel(level: number): Module[] {
  return modules.filter((m) => m.level === level);
}

export function getModulesByWeek(week: number): Module[] {
  return modules.filter((m) => m.week === week);
}

export function getPrerequisiteModules(id: string): Module[] {
  const mod = getModule(id);
  if (!mod) return [];
  return mod.prerequisites
    .map((prereqId) => getModule(prereqId))
    .filter((m): m is Module => m !== undefined);
}

export function getDependentModules(id: string): Module[] {
  return modules.filter((m) => m.prerequisites.includes(id));
}
